// The color themes of the desktop app, as data: theme.ts turns each one into the `--vscode-*` variables. A theme is
// the base of its kind (VS Code's default dark or light colors) with either exact colors over it, or a short palette
// the rest is derived from. No vscode or Electron dependency.
import type { ThemeKind } from './protocol';

export interface SyntaxColors {
  comment: string;
  string: string;
  number: string;
  keyword: string;
  control: string;
  constant: string;
  variable: string;
  property: string;
  function: string;
  type: string;
  regexp: string;
}

/** The few colors a theme is made from; theme.ts derives the others. All `#rrggbb`. */
export interface Palette {
  /** The editor, the selected tab, the content of the tabs. */
  background: string;
  /** The side bar, the strip of the tabs, the status bar, the widgets. */
  surface: string;
  foreground: string;
  /** Descriptions, line numbers, the names of the other tabs. */
  muted: string;
  border: string;
  /** The line above the selected tab, the progress bar; also the focus unless `focus` says otherwise. */
  accent: string;
  focus?: string;
  link?: string;
  button: string;
  buttonForeground: string;
  input: string;
  inputBorder: string;
  /** The selected row of a list or of the tree. */
  selection: string;
  selectionForeground: string;
  hover: string;
  /** The selected text in the editor. */
  editorSelection: string;
  /** The theme's own red, blue, yellow, orange, green and purple (the presets and the conditional formats). */
  charts?: Partial<Record<'red' | 'blue' | 'yellow' | 'orange' | 'green' | 'purple', string>>;
}

export interface ThemeDefinition {
  /** The value of the `app.theme` setting. */
  id: string;
  label: string;
  kind: ThemeKind;
  palette?: Palette;
  /** Exact colors, over the base and over what the palette gives. */
  colors?: Record<string, string>;
  syntax: SyntaxColors;
  /** The background around the panels in the islands layout; derived from the side bar when missing. */
  window?: string;
  /** A line around each panel in the islands layout, for the themes whose panels and window are the same color. */
  islandBorder?: string;
}

