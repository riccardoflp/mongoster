/** The theme as a VS Code color theme file: what the extension reads the syntax colors from. */
export function themeFile(kind: ThemeKind): string {
  const c = SYNTAX[kind];
  const rule = (scope: string[], foreground: string) => ({ scope, settings: { foreground } });
  return JSON.stringify({
    name: THEME_NAMES[kind],
    tokenColors: [
      rule(['comment'], c.comment),
      rule(['string'], c.string),
      rule(['constant.numeric'], c.number),
      rule(['constant.language'], c.constant),
      rule(['keyword', 'storage'], c.keyword),
      rule(['keyword.control'], c.control),
      rule(['variable'], c.variable),
      rule(['support.type.property-name'], c.property),
      rule(['entity.name.function', 'support.function'], c.function),
      rule(['entity.name.type', 'support.class', 'support.type'], c.type),
      rule(['string.regexp'], c.regexp),
    ],
  });
}
